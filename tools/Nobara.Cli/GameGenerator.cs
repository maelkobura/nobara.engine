using System.Security;
using System.Text;
using Nobara.ResourceCompiler;

namespace Nobara.Cli;

/// <summary>
/// <c>nobara generate</c> for a game: resolves its modules, then writes the
/// solution, the module map, the lock file, and the entry assembly.
/// </summary>
internal static class GameGenerator
{
    /// <summary>The suffixes of the auxiliary projects that the solution lists next to their module.</summary>
    public static readonly string[] AuxiliarySuffixes = [".Build", ".Generators", ".Analyzers", ".Scripting", ".TypeGen", ".Tests", ".Benchmarks"];

    /// <summary>Gets the version of the core and of the hot reload library that a game without a clone of the engine uses: the version of this tool.</summary>
    public static string EngineVersion
    {
        get
        {
            Version version = typeof(GameGenerator).Assembly.GetName().Version ?? new Version(1, 0, 0);
            return $"{version.Major}.{version.Minor}.{version.Build}";
        }
    }

    /// <summary>Generates the files of a game.</summary>
    /// <param name="files">The game.</param>
    /// <param name="check">
    /// Whether the solution and the lock file, which are kept in version
    /// control, are only compared with what would be generated. Files under
    /// <c>obj/</c> are written either way.
    /// </param>
    /// <param name="reporter">Receives the progress and the problems.</param>
    /// <returns>The resolved modules, or <see langword="null"/> on failure.</returns>
    public static Resolution? Generate(GameFiles files, bool check, Reporter reporter)
    {
        var diagnostics = new DiagnosticBag();
        string lockPath = Path.Combine(files.Root, GameFiles.LockFile);
        IReadOnlyList<LockedModule>? locked = LockFile.Read(lockPath, out string? lockProblem);
        if (lockProblem is not null)
        {
            reporter.Warning($"{lockPath} is ignored: {lockProblem}");
        }

        Resolution? resolution = ModuleResolver.Resolve(files, locked, reporter, diagnostics);
        if (!reporter.Report(diagnostics.Items) || resolution is null)
        {
            return null;
        }

        Directory.CreateDirectory(files.EntryDirectory);
        Files.WriteIfChanged(Path.Combine(files.Generated, "modules.props"), ModuleMap(files.Generated, resolution));

        bool icon = WriteIcon(files, reporter);
        Files.WriteIfChanged(files.EntryProject, EntryAssembly.Project(files, resolution.EngineRoot, EngineVersion, icon));
        Files.WriteIfChanged(Path.Combine(files.EntryDirectory, EntryAssembly.ProgramFile), EntryAssembly.Program());
        string target = Path.Combine(files.EntryDirectory, EntryAssembly.TargetFile);
        if (!File.Exists(target))
        {
            File.WriteAllText(target, EntryAssembly.EmptyTarget());
        }

        Files.Update(files.Solution, Solution(files, resolution), check, reporter);
        Files.Update(lockPath, LockFile.Write(resolution.Modules, files.Root), check, reporter);
        if (reporter.Errors > 0)
        {
            return null;
        }

        reporter.Info($"Generated {Path.GetFileName(files.Solution)}: {resolution.Modules.Count} modules ({resolution.Modules.Count(m => m.Origin == ModuleOrigin.Local)} local, {resolution.Modules.Count(m => m.Origin == ModuleOrigin.Override)} overrides, {resolution.Modules.Count(m => m.Origin == ModuleOrigin.Package)} packages).");
        return resolution;
    }

    /// <summary>The module map that <c>Nobara.Sdk</c> imports: the project of each module that the game builds from sources.</summary>
    public static string ModuleMap(string generated, Resolution resolution)
    {
        var text = new StringBuilder();
        text.Append("<!-- Generated by nobara generate. Do not edit. -->\n<Project>\n");
        if (resolution.EngineRoot is not null)
        {
            string core = Path.Combine(resolution.EngineRoot, "src", "Core", "Nobara.Core", "Nobara.Core.csproj");
            text.Append("  <PropertyGroup>\n");
            text.Append($"    <NobaraCoreProject>{FromHere(generated, core)}</NobaraCoreProject>\n");
            text.Append("  </PropertyGroup>\n");
        }

        text.Append("  <ItemGroup>\n");
        foreach (ResolvedModule module in resolution.Modules.Where(m => m.ProjectFile is not null).OrderBy(m => m.Id, StringComparer.OrdinalIgnoreCase))
        {
            text.Append($"    <NobaraLocalModule Include=\"{module.Id}\" Project=\"{FromHere(generated, module.ProjectFile!)}\" />\n");
        }

        text.Append("  </ItemGroup>\n</Project>\n");
        return text.ToString();
    }

    /// <summary>A path written relative to the folder of the file that holds it, for MSBuild.</summary>
    public static string FromHere(string folder, string path) =>
        SecurityElement.Escape("$(MSBuildThisFileDirectory)" + Path.GetRelativePath(folder, path).Replace('\\', '/'))!;

    private static string Solution(GameFiles files, Resolution resolution)
    {
        var projects = new List<(string Folder, string Path)>();
        foreach (ResolvedModule module in resolution.Modules.Where(m => m.ProjectFile is not null))
        {
            string relative = Names.Relative(files.Root, module.ProjectFile!);
            string folder = relative.StartsWith("../", StringComparison.Ordinal)
                ? "/engine/"
                : "/" + string.Join('/', relative.Split('/').SkipLast(2)) + "/";
            projects.Add((folder.Replace("//", "/", StringComparison.Ordinal), relative));
            foreach (string auxiliary in Auxiliaries(module.ProjectFile!))
            {
                projects.Add((folder.Replace("//", "/", StringComparison.Ordinal), Names.Relative(files.Root, auxiliary)));
            }
        }

        projects.Add(("/entry/", Names.Relative(files.Root, files.EntryProject)));
        return SolutionFile.Write(projects, "Generated by nobara generate from project.nobara. Do not edit.");
    }

    // The auxiliary projects next to the project of a module: Example.Mobs.Tests next to Example.Mobs.
    private static IEnumerable<string> Auxiliaries(string projectFile)
    {
        string folder = Path.GetDirectoryName(projectFile)!;
        string name = Path.GetFileName(folder);
        string parent = Path.GetDirectoryName(folder)!;
        foreach (string suffix in AuxiliarySuffixes)
        {
            string candidate = Path.Combine(parent, name + suffix, name + suffix + ".csproj");
            if (File.Exists(candidate))
            {
                yield return candidate;
            }
        }
    }

    private static bool WriteIcon(GameFiles files, Reporter reporter)
    {
        string target = Path.Combine(files.EntryDirectory, EntryAssembly.IconFile);
        if (files.Project.Icon is not string icon)
        {
            File.Delete(target);
            return false;
        }

        string source = Path.GetFullPath(Path.Combine(files.Root, icon));
        byte[]? content = File.Exists(source) ? IconFile.FromPng(File.ReadAllBytes(source), out string? error) : null;
        if (content is null)
        {
            reporter.Error($"{Path.Combine(files.Root, GameFiles.ProjectFile)}: the icon '{icon}' cannot be used: {(File.Exists(source) ? "it is not a PNG image of at most 256x256 pixels" : "the file does not exist")}");
            return false;
        }

        Files.WriteIfChanged(target, content);
        return true;
    }
}

/// <summary>Writes generated files.</summary>
internal static class Files
{
    /// <summary>Writes a file unless it already has this content, so its time stamp stays.</summary>
    public static void WriteIfChanged(string path, string content) => WriteIfChanged(path, Encoding.UTF8.GetBytes(content));

    public static void WriteIfChanged(string path, byte[] content)
    {
        if (File.Exists(path) && File.ReadAllBytes(path).AsSpan().SequenceEqual(content))
        {
            return;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllBytes(path, content);
    }

    /// <summary>Writes a file kept in version control, or, in check mode, reports it when it is out of date.</summary>
    public static void Update(string path, string content, bool check, Reporter reporter)
    {
        if (!check)
        {
            WriteIfChanged(path, content);
            return;
        }

        string? current = File.Exists(path) ? File.ReadAllText(path).Replace("\r\n", "\n", StringComparison.Ordinal) : null;
        if (current != content)
        {
            reporter.Error($"{path} is out of date: run nobara generate and commit the result.");
        }
    }
}

/// <summary>Writes a solution in the <c>.slnx</c> format.</summary>
internal static class SolutionFile
{
    public static string Write(IEnumerable<(string Folder, string Path)> projects, string comment)
    {
        var text = new StringBuilder();
        text.Append($"<!-- {comment} -->\n<Solution>\n");
        foreach (IGrouping<string, (string Folder, string Path)> folder in projects
            .DistinctBy(p => p.Path, StringComparer.OrdinalIgnoreCase)
            .GroupBy(p => p.Folder, StringComparer.Ordinal)
            .OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            text.Append($"  <Folder Name=\"{SecurityElement.Escape(folder.Key)}\">\n");

            // Segment by segment: Example.Mobs/ comes before Example.Mobs.Tests/.
            foreach ((_, string path) in folder.OrderBy(p => p.Path.Replace('/', '\u0001'), StringComparer.Ordinal))
            {
                text.Append($"    <Project Path=\"{SecurityElement.Escape(path)}\" />\n");
            }

            text.Append("  </Folder>\n");
        }

        text.Append("</Solution>\n");
        return text.ToString();
    }
}
