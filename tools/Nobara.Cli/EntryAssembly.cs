using System.Security;

namespace Nobara.Cli;

/// <summary>
/// The generated entry assembly of a game: its project, its <c>main()</c> for
/// each side, and the file that each build of a target rewrites.
/// </summary>
internal static class EntryAssembly
{
    public const string ClientProgram = "Nobara.Entry.ClientProgram";
    public const string ServerProgram = "Nobara.Entry.ServerProgram";
    public const string TargetFile = "target.props";
    public const string ProgramFile = "Program.g.cs";
    public const string IconFile = "icon.ico";

    /// <summary>The project file. The core and the hot reload library are projects of a clone of the engine, or packages.</summary>
    public static string Project(GameFiles files, string? engineRoot, string engineVersion, bool icon)
    {
        string core = engineRoot is null
            ? $"""    <PackageReference Include="Nobara.Core" Version="{engineVersion}" />"""
            : $"""    <ProjectReference Include="{Escape(Path.Combine(engineRoot, "src", "Core", "Nobara.Core", "Nobara.Core.csproj"))}" />""";
        string hotReload = engineRoot is null
            ? $"""    <PackageReference Include="Nobara.HotReload" Version="{engineVersion}" />"""
            : $"""    <ProjectReference Include="{Escape(Path.Combine(engineRoot, "tools", "Nobara.HotReload", "Nobara.HotReload.csproj"))}" />""";
        string iconProperty = icon ? $"\n    <ApplicationIcon>{IconFile}</ApplicationIcon>" : string.Empty;
        return $"""
            <!--
              Generated by nobara generate from project.nobara. Do not edit.
              The entry assembly of the game: the main() of each side. Each build
              of a target rewrites {TargetFile} with its modules and settings.
            -->
            <Project Sdk="Microsoft.NET.Sdk">

              <PropertyGroup>
                <OutputType>Exe</OutputType>
                <TargetFramework>net10.0</TargetFramework>
                <Nullable>enable</Nullable>
                <ImplicitUsings>disable</ImplicitUsings>
                <AssemblyName>{files.EntryName}</AssemblyName>
                <RootNamespace>Nobara.Entry</RootNamespace>
                <Product>{Escape(files.Project.Name)}</Product>
                <Version>{files.Project.Version.Text}</Version>
                <IsPackable>false</IsPackable>
                <StartupObject>{ClientProgram}</StartupObject>
                <NobaraDevelopment>false</NobaraDevelopment>{iconProperty}
              </PropertyGroup>

              <Import Project="{TargetFile}" Condition="Exists('{TargetFile}')" />

              <PropertyGroup Condition="'$(NobaraDevelopment)' == 'true'">
                <DefineConstants>$(DefineConstants);NOBARA_DEVELOPMENT</DefineConstants>
              </PropertyGroup>

              <ItemGroup>
            {core}
              </ItemGroup>

              <ItemGroup Condition="'$(NobaraDevelopment)' == 'true'">
            {hotReload}
              </ItemGroup>

              <ItemGroup>
                <EmbeddedResource Include="$(NobaraDistributionManifest)" LogicalName="nobara/distribution.pb" Condition="'$(NobaraDistributionManifest)' != ''" />
                <EmbeddedResource Include="$(NobaraHotReloadMap)" LogicalName="nobara/hot-reload.json" Condition="'$(NobaraHotReloadMap)' != ''" />
              </ItemGroup>

            </Project>

            """;
    }

    /// <summary>The <c>main()</c> of the client and of the server.</summary>
    public static string Program() => """
        // <auto-generated>
        // Generated by nobara generate. Do not edit.
        // </auto-generated>

        using System;
        using Nobara.Core;

        namespace Nobara.Entry;

        /// <summary>The main() of the client.</summary>
        public static class ClientProgram
        {
            /// <summary>Starts the game.</summary>
            public static int Main(string[] args) => EntryPoint.Run(Side.Client, args);
        }

        /// <summary>The main() of the dedicated server.</summary>
        public static class ServerProgram
        {
            /// <summary>Starts the server.</summary>
            public static int Main(string[] args) => EntryPoint.Run(Side.Server, args);
        }

        internal static class EntryPoint
        {
            private const string HotReloadOption = "--hot-reload";
            private const string ProfileOption = "--profile";

            public static int Run(Side side, string[] args)
            {
                bool profiling = Array.IndexOf(args, ProfileOption) >= 0;
        #if NOBARA_DEVELOPMENT
                if (Array.IndexOf(args, HotReloadOption) >= 0)
                {
                    using var hotReload = new Nobara.HotReload.HotReloadHost(typeof(EntryPoint).Assembly);
                    return Engine.Run(new EngineOptions { Side = side, DevelopmentMode = true, Profiling = profiling, OnLoaded = hotReload.Attach });
                }
        #else
                if (Array.IndexOf(args, HotReloadOption) >= 0)
                {
                    Console.Error.WriteLine(HotReloadOption + " needs a development build: nobara build --development.");
                    return 1;
                }
        #endif

                return Engine.Run(new EngineOptions { Side = side, Profiling = profiling });
            }
        }

        """;

    /// <summary>The file that a build of a target writes before it publishes the entry assembly.</summary>
    public static string Target(TargetSettings settings)
    {
        var lines = new List<string>
        {
            "<!-- Written by nobara build for one target. Do not edit. -->",
            "<Project>",
            "  <PropertyGroup>",
            $"    <RuntimeIdentifier>{settings.Platform}</RuntimeIdentifier>",
            "    <SelfContained>true</SelfContained>",
            $"    <PublishReadyToRun>{(settings.Development ? "false" : "true")}</PublishReadyToRun>",
            $"    <StartupObject>{(settings.Server ? ServerProgram : ClientProgram)}</StartupObject>",
            $"    <NobaraDevelopment>{(settings.Development ? "true" : "false")}</NobaraDevelopment>",
        };
        if (settings.DistributionManifest is not null)
        {
            lines.Add($"    <NobaraDistributionManifest>{Escape(settings.DistributionManifest)}</NobaraDistributionManifest>");
        }

        if (settings.HotReloadMap is not null)
        {
            lines.Add($"    <NobaraHotReloadMap>{Escape(settings.HotReloadMap)}</NobaraHotReloadMap>");
        }

        lines.Add("  </PropertyGroup>");
        lines.Add("  <ItemGroup>");
        lines.AddRange(settings.Projects.Select(p => $"    <ProjectReference Include=\"{Escape(p)}\" />"));
        lines.AddRange(settings.Packages.Select(p => $"    <PackageReference Include=\"{Escape(p.Id)}\" Version=\"[{Escape(p.Version)}]\" />"));
        lines.Add("  </ItemGroup>");
        lines.Add("</Project>");
        return string.Join('\n', lines) + "\n";
    }

    /// <summary>The empty target file that <c>nobara generate</c> writes, so the entry project builds alone in the IDE.</summary>
    public static string EmptyTarget() => "<!-- Written by nobara build for one target. Do not edit. -->\n<Project>\n</Project>\n";

    private static string Escape(string text) => SecurityElement.Escape(text)!;
}

/// <summary>What one build of a target puts in the entry project.</summary>
internal sealed class TargetSettings
{
    public required string Platform { get; init; }

    public required bool Server { get; init; }

    public required bool Development { get; init; }

    public required IReadOnlyList<string> Projects { get; init; }

    public required IReadOnlyList<(string Id, string Version)> Packages { get; init; }

    public string? DistributionManifest { get; init; }

    public string? HotReloadMap { get; init; }
}
