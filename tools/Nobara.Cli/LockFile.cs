using System.Text;
using System.Xml;
using System.Xml.Linq;

namespace Nobara.Cli;

/// <summary>One module of <c>project.nobara.lock</c>.</summary>
internal sealed record LockedModule(string Id, string Version, ModuleOrigin Origin, string? Path, bool Transitive);

/// <summary>
/// <c>project.nobara.lock</c>: the modules of a game, transitive ones
/// included, with the version each resolved to.
/// </summary>
internal static class LockFile
{
    public const int Format = 1;

    /// <summary>Reads a lock file.</summary>
    /// <returns>The modules, or <see langword="null"/> when the file is missing or cannot be read; <paramref name="problem"/> says why it cannot.</returns>
    public static IReadOnlyList<LockedModule>? Read(string path, out string? problem)
    {
        problem = null;
        if (!File.Exists(path))
        {
            return null;
        }

        try
        {
            XElement root = XDocument.Load(path).Root!;
            if (root.Name.LocalName != "NobaraLock" || (string?)root.Attribute("format") != Format.ToString(System.Globalization.CultureInfo.InvariantCulture))
            {
                problem = $"it is not a lock file of format {Format}";
                return null;
            }

            return root.Elements("Module").Select(e => new LockedModule(
                (string?)e.Attribute("id") ?? throw new FormatException("a <Module> has no id"),
                (string?)e.Attribute("version") ?? throw new FormatException("a <Module> has no version"),
                ((string?)e.Attribute("source")) switch
                {
                    "local" => ModuleOrigin.Local,
                    "override" => ModuleOrigin.Override,
                    "package" => ModuleOrigin.Package,
                    var other => throw new FormatException($"unknown source '{other}'"),
                },
                (string?)e.Attribute("path"),
                (bool?)e.Attribute("transitive") ?? false)).ToList();
        }
        catch (Exception exception) when (exception is XmlException or IOException or FormatException or UnauthorizedAccessException)
        {
            problem = exception.Message;
            return null;
        }
    }

    /// <summary>Writes the lock file of a resolution, sorted by identifier.</summary>
    public static string Write(IEnumerable<ResolvedModule> modules, string root)
    {
        var document = new XElement(
            "NobaraLock",
            new XAttribute("format", Format),
            modules.OrderBy(m => m.Id, StringComparer.OrdinalIgnoreCase).Select(m => new XElement(
                "Module",
                new XAttribute("id", m.Id),
                new XAttribute("version", m.Version),
                new XAttribute("source", m.Origin.ToString().ToLowerInvariant()),
                m.Folder is null ? null : new XAttribute("path", Names.Relative(root, m.Folder)),
                m.Transitive ? new XAttribute("transitive", "true") : null)));

        var text = new StringBuilder();
        text.Append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
        text.Append("<!-- Generated by nobara generate: the modules of the game and their resolved versions. Do not edit. -->\n");
        text.Append(document.ToString().Replace("\r\n", "\n", StringComparison.Ordinal));
        text.Append('\n');
        return text.ToString();
    }
}
