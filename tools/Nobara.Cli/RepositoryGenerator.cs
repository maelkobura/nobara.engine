using System.Text;
using Nobara.ResourceCompiler;
using Nobara.ResourceCompiler.Manifests;

namespace Nobara.Cli;

/// <summary>
/// <c>nobara generate</c> for the engine repository, which has no
/// <c>project.nobara</c>: the solution lists the projects found under
/// <c>src/</c> and <c>tools/</c>, and the module map lists the modules among
/// them.
/// </summary>
/// <remarks>
/// A project is <c>src/&lt;folder&gt;/&lt;name&gt;/&lt;name&gt;.csproj</c> or
/// <c>tools/&lt;name&gt;/&lt;name&gt;.csproj</c>; deeper projects, such as
/// sample modules of tests, are left out. A project is a module when a
/// <c>module.nobara</c> sits next to it.
/// </remarks>
internal static class RepositoryGenerator
{
    public const string SolutionName = "Nobara.slnx";

    /// <summary>Tells whether a folder is a repository that this generator handles: no <c>project.nobara</c>, and a <c>src/</c> or <c>tools/</c> folder.</summary>
    public static bool Applies(string root) =>
        !File.Exists(Path.Combine(root, GameFiles.ProjectFile))
        && (Directory.Exists(Path.Combine(root, "src")) || Directory.Exists(Path.Combine(root, "tools")));

    /// <summary>Generates the solution and the module map of the repository.</summary>
    /// <returns><see langword="true"/> on success.</returns>
    public static bool Generate(string root, bool check, Reporter reporter)
    {
        var projects = new List<(string Folder, string Path)>();
        var modules = new List<(string Id, string Project)>();
        var diagnostics = new DiagnosticBag();
        foreach (string project in Projects(root))
        {
            string relative = Names.Relative(root, project);
            string[] parts = relative.Split('/');
            projects.Add((parts[0] == "src" ? $"/src/{parts[1]}/" : "/tools/", relative));

            string folder = Path.GetDirectoryName(project)!;
            if (File.Exists(Path.Combine(folder, "module.nobara")) && GameFiles.ReadModule(folder, diagnostics) is ModuleManifest manifest)
            {
                modules.Add((manifest.Id, project));
            }
        }

        if (!reporter.Report(diagnostics.Items))
        {
            return false;
        }

        string generated = Path.Combine(root, "obj", "nobara");
        Files.WriteIfChanged(Path.Combine(generated, "modules.props"), ModuleMap(root, generated, modules));
        Files.Update(Path.Combine(root, SolutionName), SolutionFile.Write(projects, "Generated by nobara generate from the projects under src/ and tools/. Do not edit."), check, reporter);
        if (reporter.Errors > 0)
        {
            return false;
        }

        reporter.Info($"Generated {SolutionName}: {projects.Count} projects, {modules.Count} modules.");
        return true;
    }

    private static IEnumerable<string> Projects(string root)
    {
        string src = Path.Combine(root, "src");
        if (Directory.Exists(src))
        {
            foreach (string folder in Directory.EnumerateDirectories(src).Order(StringComparer.Ordinal))
            {
                foreach (string project in Directory.EnumerateDirectories(folder).Order(StringComparer.Ordinal).Select(Own).OfType<string>())
                {
                    yield return project;
                }
            }
        }

        string tools = Path.Combine(root, "tools");
        if (Directory.Exists(tools))
        {
            foreach (string project in Directory.EnumerateDirectories(tools).Order(StringComparer.Ordinal).Select(Own).OfType<string>())
            {
                yield return project;
            }
        }
    }

    // The project named after its folder, if any.
    private static string? Own(string folder)
    {
        string project = Path.Combine(folder, Path.GetFileName(folder) + ".csproj");
        return File.Exists(project) ? Path.GetFullPath(project) : null;
    }

    private static string ModuleMap(string root, string generated, List<(string Id, string Project)> modules)
    {
        var text = new StringBuilder();
        text.Append("<!-- Generated by nobara generate. Do not edit. -->\n<Project>\n");
        string core = Path.Combine(root, "src", "Core", "Nobara.Core", "Nobara.Core.csproj");
        if (File.Exists(core))
        {
            text.Append($"  <PropertyGroup>\n    <NobaraCoreProject>{GameGenerator.FromHere(generated, core)}</NobaraCoreProject>\n  </PropertyGroup>\n");
        }

        text.Append("  <ItemGroup>\n");
        foreach ((string id, string project) in modules.OrderBy(m => m.Id, StringComparer.OrdinalIgnoreCase))
        {
            text.Append($"    <NobaraLocalModule Include=\"{id}\" Project=\"{GameGenerator.FromHere(generated, project)}\" />\n");
        }

        text.Append("  </ItemGroup>\n</Project>\n");
        return text.ToString();
    }
}
