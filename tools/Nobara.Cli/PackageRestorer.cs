using System.Security;
using System.Text.Json;
using Nobara.ResourceCompiler;

namespace Nobara.Cli;

/// <summary>
/// Restores module packages with NuGet, through a project generated in
/// <c>obj/nobara/restore/</c>, so that the sources and the cache of the game
/// apply.
/// </summary>
internal static class PackageRestorer
{
    /// <summary>Restores packages.</summary>
    /// <param name="files">The game.</param>
    /// <param name="versions">The NuGet version or range of each package.</param>
    /// <param name="reporter">Receives the output of NuGet.</param>
    /// <param name="diagnostics">Receives the problems.</param>
    /// <returns>For each package, the version NuGet chose and its assembly named after the package, or <see langword="null"/> on failure.</returns>
    public static IReadOnlyDictionary<string, (string Version, string? Assembly)>? Restore(
        GameFiles files, IReadOnlyDictionary<string, string> versions, Reporter reporter, DiagnosticBag diagnostics)
    {
        string folder = Path.Combine(files.Generated, "restore");
        Directory.CreateDirectory(folder);
        string project = Path.Combine(folder, "ModulePackages.csproj");
        string references = string.Concat(versions.OrderBy(v => v.Key, StringComparer.OrdinalIgnoreCase)
            .Select(v => $"    <PackageReference Include=\"{SecurityElement.Escape(v.Key)}\" Version=\"{SecurityElement.Escape(v.Value)}\" />\n"));
        File.WriteAllText(project, $"""
            <!-- Generated by nobara: restores the module packages of the game. Do not edit. -->
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <IsPackable>false</IsPackable>
              </PropertyGroup>
              <ItemGroup>
            {references}  </ItemGroup>
            </Project>

            """);

        if (Dotnet.Run(reporter, folder, "restore", project, "--nologo", "-v:q") != 0)
        {
            diagnostics.Error(CliCodes.Restore, "the module packages cannot be restored; see the NuGet errors above", new Location(Path.Combine(files.Root, GameFiles.ProjectFile), 0, 0));
            return null;
        }

        string assets = Path.Combine(folder, "obj", "project.assets.json");
        using JsonDocument document = JsonDocument.Parse(File.ReadAllText(assets));
        JsonElement root = document.RootElement;
        string packageFolder = root.GetProperty("packageFolders").EnumerateObject().First().Name;
        JsonElement libraries = root.GetProperty("libraries");
        JsonElement target = root.GetProperty("targets").EnumerateObject().First().Value;

        var result = new Dictionary<string, (string Version, string? Assembly)>(StringComparer.OrdinalIgnoreCase);
        foreach (JsonProperty package in target.EnumerateObject())
        {
            int slash = package.Name.IndexOf('/', StringComparison.Ordinal);
            string id = package.Name[..slash];
            string version = package.Name[(slash + 1)..];
            if (!versions.ContainsKey(id))
            {
                continue;
            }

            string? assembly = null;
            if (package.Value.TryGetProperty("runtime", out JsonElement runtime))
            {
                string relative = libraries.GetProperty(package.Name).GetProperty("path").GetString()!;
                string? asset = runtime.EnumerateObject().Select(a => a.Name)
                    .FirstOrDefault(a => string.Equals(Path.GetFileNameWithoutExtension(a), id, StringComparison.OrdinalIgnoreCase) && a.EndsWith(".dll", StringComparison.OrdinalIgnoreCase));
                if (asset is not null)
                {
                    assembly = Path.GetFullPath(Path.Combine(packageFolder, relative, asset));
                }
            }

            result[id] = (version, assembly);
        }

        return result;
    }
}
