using System.Buffers.Binary;

namespace Nobara.Cli.Tests;

/// <summary><c>nobara generate</c> on sample games and on a sample engine repository.</summary>
public sealed class GenerateTests : IDisposable
{
    private readonly GameFolder _game = new();

    public void Dispose() => _game.Dispose();

    private static string Depends(string id, string range = "^1.0", bool optional = false) =>
        $"""<Dependencies><Module id="{id}" version="{range}" optional="{(optional ? "true" : "false")}" /></Dependencies>""";

    [Fact]
    public void Generates_the_solution_the_module_map_the_lock_file_and_the_entry_assembly()
    {
        _game.Project("""<Local path="src/Example.Mobs" /><Local path="src/Example.Zombie" required="true" />""")
            .Module("src/Example.Mobs", "example.mobs")
            .Module("src/Example.Zombie", "example.zombie", Depends("example.mobs"));
        _game.Write("src/Example.Mobs.Tests/Example.Mobs.Tests.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");

        CliResult result = _game.Run("generate");

        Assert.True(result.ExitCode == 0, result.ToString());
        Assert.Contains("Generated Example Game.slnx: 2 modules (2 local, 0 overrides, 0 packages).", result.Output, StringComparison.Ordinal);
        Assert.Equal("""
            <!-- Generated by nobara generate from project.nobara. Do not edit. -->
            <Solution>
              <Folder Name="/entry/">
                <Project Path="obj/nobara/entry/ExampleGame.csproj" />
              </Folder>
              <Folder Name="/src/">
                <Project Path="src/Example.Mobs/example.mobs.csproj" />
                <Project Path="src/Example.Mobs.Tests/Example.Mobs.Tests.csproj" />
                <Project Path="src/Example.Zombie/example.zombie.csproj" />
              </Folder>
            </Solution>

            """.ReplaceLineEndings("\n"), _game.Read("Example Game.slnx"));
        Assert.Equal("""
            <!-- Generated by nobara generate. Do not edit. -->
            <Project>
              <ItemGroup>
                <NobaraLocalModule Include="example.mobs" Project="$(MSBuildThisFileDirectory)../../src/Example.Mobs/example.mobs.csproj" />
                <NobaraLocalModule Include="example.zombie" Project="$(MSBuildThisFileDirectory)../../src/Example.Zombie/example.zombie.csproj" />
              </ItemGroup>
            </Project>

            """.ReplaceLineEndings("\n"), _game.Read("obj/nobara/modules.props"));
        string lockFile = _game.Read("project.nobara.lock");
        Assert.Contains("""<Module id="example.mobs" version="1.0.0" source="local" path="src/Example.Mobs" />""", lockFile, StringComparison.Ordinal);
        Assert.Contains("""<Module id="example.zombie" version="1.0.0" source="local" path="src/Example.Zombie" />""", lockFile, StringComparison.Ordinal);

        string entry = _game.Read("obj/nobara/entry/ExampleGame.csproj");
        Assert.Contains("<AssemblyName>ExampleGame</AssemblyName>", entry, StringComparison.Ordinal);
        Assert.Contains("""<PackageReference Include="Nobara.Core" Version="1.0.0" />""", entry, StringComparison.Ordinal);
        Assert.Contains("""<PackageReference Include="Nobara.HotReload" Version="1.0.0" />""", entry, StringComparison.Ordinal);
        string program = _game.Read("obj/nobara/entry/Program.g.cs");
        Assert.Contains("public static int Main(string[] args) => EntryPoint.Run(Side.Client, args);", program, StringComparison.Ordinal);
        Assert.Contains("public static int Main(string[] args) => EntryPoint.Run(Side.Server, args);", program, StringComparison.Ordinal);
        Assert.True(_game.Exists("obj/nobara/entry/target.props"));
    }

    [Fact]
    public void Builds_against_the_engine_sources_that_an_override_points_into()
    {
        _game.Write("engine/src/Core/Nobara.Core/Nobara.Core.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        _game.Module("engine/src/Game/Nobara.Game", "nobara.game", Depends("nobara.events"), level: "platform")
            .Module("engine/src/Events/Nobara.Events", "nobara.events", level: "platform")
            .Module("game/src/Example.Mobs", "example.mobs", Depends("nobara.game"));
        _game.Write("game/project.nobara", """
            <NobaraProject format="1"><Id>example.game</Id><Name>Example</Name><Version>0.1.0</Version>
              <Modules><Local path="src/Example.Mobs" /><Package id="nobara.game" version="^1.0" /></Modules>
              <Overrides>
                <Project id="nobara.game" path="../engine/src/Game/Nobara.Game" />
                <Project id="nobara.events" path="../engine/src/Events/Nobara.Events" />
              </Overrides>
            </NobaraProject>
            """);
        string game = Path.Combine(_game.Root, "game");

        CliResult result = GameFolder.RunIn(game, "generate");

        Assert.True(result.ExitCode == 0, result.ToString());
        string map = _game.Read("game/obj/nobara/modules.props");
        Assert.Contains("<NobaraCoreProject>$(MSBuildThisFileDirectory)../../../engine/src/Core/Nobara.Core/Nobara.Core.csproj</NobaraCoreProject>", map, StringComparison.Ordinal);
        Assert.Contains("""<NobaraLocalModule Include="nobara.events" Project="$(MSBuildThisFileDirectory)../../../engine/src/Events/Nobara.Events/nobara.events.csproj" />""", map, StringComparison.Ordinal);
        string lockFile = _game.Read("game/project.nobara.lock");
        Assert.Contains("""<Module id="nobara.events" version="1.0.0" source="override" path="../engine/src/Events/Nobara.Events" transitive="true" />""", lockFile, StringComparison.Ordinal);
        Assert.Contains("""<Module id="nobara.game" version="1.0.0" source="override" path="../engine/src/Game/Nobara.Game" />""", lockFile, StringComparison.Ordinal);
        string entry = _game.Read("game/obj/nobara/entry/Example.csproj");
        Assert.Contains(Path.Combine(_game.Root, "engine", "src", "Core", "Nobara.Core", "Nobara.Core.csproj"), entry, StringComparison.Ordinal);
        Assert.Contains(Path.Combine(_game.Root, "engine", "tools", "Nobara.HotReload", "Nobara.HotReload.csproj"), entry, StringComparison.Ordinal);
        Assert.Contains("""<Folder Name="/engine/">""", _game.Read("game/Example.slnx"), StringComparison.Ordinal);
    }

    [Fact]
    public void Checks_the_files_kept_in_version_control_without_changing_them()
    {
        _game.Project("""<Local path="src/Example.Mobs" />""").Module("src/Example.Mobs", "example.mobs");
        Assert.Equal(0, _game.Run("generate").ExitCode);
        Assert.Equal(0, _game.Run("generate", "--check").ExitCode);

        _game.Module("src/Example.Mobs", "example.mobs", version: "1.1.0");
        CliResult result = _game.Run("generate", "--check");

        Assert.Equal(1, result.ExitCode);
        Assert.Contains($"{Path.Combine(_game.Root, "project.nobara.lock")} is out of date: run nobara generate", result.Errors, StringComparison.Ordinal);
        Assert.Contains("version=\"1.0.0\"", _game.Read("project.nobara.lock"), StringComparison.Ordinal);
    }

    [Fact]
    public void Names_the_folder_of_a_local_module_without_manifest_or_project()
    {
        _game.Project("""<Local path="src/Example.Mobs" /><Local path="src/Example.Ghost" />""");
        _game.Write("src/Example.Mobs/module.nobara", """<NobaraModule format="1"><Id>example.mobs</Id><Version>1.0.0</Version><Level>business</Level><Side>both</Side></NobaraModule>""");
        Directory.CreateDirectory(Path.Combine(_game.Root, "src", "Example.Ghost"));

        CliResult result = _game.Run("generate");

        Assert.Equal(1, result.ExitCode);
        Assert.Contains("error NCLI003: module 'example.mobs' has no project file 'example.mobs.csproj'", result.Errors, StringComparison.Ordinal);
        Assert.Contains(Path.Combine(_game.Root, "src", "Example.Ghost", "module.nobara") + ": error NRC001: module.nobara not found", result.Errors, StringComparison.Ordinal);
    }

    [Fact]
    public void Turns_the_icon_into_the_icon_of_the_executable()
    {
        var png = new byte[33];
        new byte[] { 0x89, (byte)'P', (byte)'N', (byte)'G', 0x0D, 0x0A, 0x1A, 0x0A, 0, 0, 0, 13, (byte)'I', (byte)'H', (byte)'D', (byte)'R' }.CopyTo(png, 0);
        BinaryPrimitives.WriteInt32BigEndian(png.AsSpan(16), 32);
        BinaryPrimitives.WriteInt32BigEndian(png.AsSpan(20), 32);
        Directory.CreateDirectory(Path.Combine(_game.Root, "assets"));
        File.WriteAllBytes(Path.Combine(_game.Root, "assets", "icon.png"), png);
        _game.Project("""<Local path="src/Example.Mobs" />""", "<Icon>assets/icon.png</Icon>").Module("src/Example.Mobs", "example.mobs");

        CliResult result = _game.Run("generate");

        Assert.True(result.ExitCode == 0, result.ToString());
        byte[] icon = File.ReadAllBytes(Path.Combine(_game.Root, "obj", "nobara", "entry", "icon.ico"));
        Assert.Equal([0, 0, 1, 0, 1, 0, 32, 32], icon[..8]);
        Assert.Equal(png, icon[22..]);
        Assert.Contains("<ApplicationIcon>icon.ico</ApplicationIcon>", _game.Read("obj/nobara/entry/ExampleGame.csproj"), StringComparison.Ordinal);
    }

    [Fact]
    public void Generates_the_solution_and_the_module_map_of_the_engine_repository()
    {
        _game.Write("src/Core/Nobara.Core/Nobara.Core.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        _game.Write("src/Core/Nobara.Core.Tests/Nobara.Core.Tests.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        _game.Write("src/Core/Nobara.Core.Tests/TestModules/Example.Base/Example.Base.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        _game.Module("src/nGame/Nobara.Game", "nobara.game", level: "platform");
        File.Move(Path.Combine(_game.Root, "src/nGame/Nobara.Game/nobara.game.csproj"), Path.Combine(_game.Root, "src/nGame/Nobara.Game/Nobara.Game.csproj"));
        _game.Write("tools/Nobara.Cli/Nobara.Cli.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");

        CliResult result = _game.Run("generate");

        Assert.True(result.ExitCode == 0, result.ToString());
        Assert.Equal("""
            <!-- Generated by nobara generate from the projects under src/ and tools/. Do not edit. -->
            <Solution>
              <Folder Name="/src/Core/">
                <Project Path="src/Core/Nobara.Core/Nobara.Core.csproj" />
                <Project Path="src/Core/Nobara.Core.Tests/Nobara.Core.Tests.csproj" />
              </Folder>
              <Folder Name="/src/nGame/">
                <Project Path="src/nGame/Nobara.Game/Nobara.Game.csproj" />
              </Folder>
              <Folder Name="/tools/">
                <Project Path="tools/Nobara.Cli/Nobara.Cli.csproj" />
              </Folder>
            </Solution>

            """.ReplaceLineEndings("\n"), _game.Read("Nobara.slnx"));
        string map = _game.Read("obj/nobara/modules.props");
        Assert.Contains("<NobaraCoreProject>$(MSBuildThisFileDirectory)../../src/Core/Nobara.Core/Nobara.Core.csproj</NobaraCoreProject>", map, StringComparison.Ordinal);
        Assert.Contains("""<NobaraLocalModule Include="nobara.game" Project="$(MSBuildThisFileDirectory)../../src/nGame/Nobara.Game/Nobara.Game.csproj" />""", map, StringComparison.Ordinal);

        _game.Write("tools/Nobara.Sdk/Nobara.Sdk.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        CliResult check = _game.Run("generate", "--check");
        Assert.Equal(1, check.ExitCode);
        Assert.Contains("Nobara.slnx is out of date", check.Errors, StringComparison.Ordinal);
    }

    [Fact]
    public void Explains_its_usage()
    {
        Assert.Equal(0, _game.Run("--help").ExitCode);
        Assert.Equal(2, _game.Run().ExitCode);
        Assert.Equal(2, _game.Run("deploy").ExitCode);
        Assert.Equal(2, _game.Run("generate", "--development").ExitCode);
        Assert.Equal(2, _game.Run("build", "--frobnicate").ExitCode);
        Assert.Equal("1.0.0", _game.Run("--version").Output.Trim());
    }
}
