namespace Nobara.Analyzers.Tests;

public sealed class StaticStateAnalyzerTests
{
    private static void Verify(string markup) =>
        AnalyzerVerifier.Verify(
            new StaticStateAnalyzer(),
            "using System; using System.Collections.Generic; using System.Collections.Frozen; using System.Collections.Immutable; using System.Text; using System.Threading;\n" + markup);

    [Fact]
    public void Accepts_constants_immutable_readonly_fields_and_instance_state()
    {
        Verify("""
            enum Face { Up, Down }
            static class Blocks
            {
                public const int Size = 16;
                public static readonly string Name = "stone";
                public static readonly TimeSpan Delay = TimeSpan.FromSeconds(1);
                public static readonly ImmutableArray<int> Faces = ImmutableArray.Create(1, 2);
                public static readonly FrozenSet<string> Tags = FrozenSet.ToFrozenSet(new[] { "a" });
                public static readonly IReadOnlyList<int> Order = new[] { 1, 2 }.AsReadOnly();
                public static readonly object Gate = new();
                public static int Twice(int x) => x * 2;
                public static int Computed => Size * 2;
                public static IReadOnlyList<int> Sizes { get; } = ImmutableArray.Create(1);
            }
            class Chunk
            {
                int _count;
                List<int> _cells = new();
                public int Count { get; set; }
                public event Action? Changed;
            }
            """);
    }

    [Fact]
    public void Reports_static_fields_that_are_not_readonly()
    {
        Verify("""
            class Counter
            {
                static int {|NOB201:s_count|};
                private static volatile bool {|NOB201:s_flag|};
                [ThreadStatic] static int {|NOB201:t_depth|};
                [ThreadStatic] static readonly string {|NOB201:t_name|} = "";
                static int {|NOB201:s_a|}, {|NOB201:s_b|};
            }
            """);
    }

    [Fact]
    public void Reports_static_properties_with_a_setter_and_static_field_like_events()
    {
        Verify("""
            static class Settings
            {
                public static int {|NOB202:Radius|} { get; set; }
                public static int {|NOB202:Height|} { get; private set; }
                public static event Action? {|NOB202:Changed|};
                public static event Action Custom { add { } remove { } }
            }
            """);
    }

    [Fact]
    public void Reports_static_readonly_members_of_a_mutable_type()
    {
        Verify("""
            class Registry : Dictionary<string, int> { }
            static class Tables
            {
                static readonly int[] {|NOB203:Lights|} = new int[16];
                static readonly List<int> {|NOB203:Ids|} = new();
                static readonly Registry {|NOB203:Names|} = new();
                static readonly IList<int> {|NOB203:Order|} = new List<int>();
                static readonly StringBuilder {|NOB203:Buffer|} = new();
                static readonly ThreadLocal<int> {|NOB203:Depth|} = new();
                static readonly Random {|NOB203:Dice|} = new(1);
                public static List<int> {|NOB203:Pending|} { get; } = new();
            }
            """);
    }

    [Fact]
    public void Names_the_mutable_type()
    {
        var diagnostic = Assert.Single(AnalyzerVerifier.Run(new StaticStateAnalyzer(), """
            using System.Collections.Generic;
            class Registry : Dictionary<string, int> { }
            static class Tables { static readonly Registry Names = new(); }
            """));

        Assert.Equal("Static readonly field 'Tables.Names' holds a mutable 'Dictionary<string, int>'", diagnostic.GetMessage());
    }

    [Fact]
    public void Skips_generated_code()
    {
        AnalyzerVerifier.Verify(new StaticStateAnalyzer(), """
            // <auto-generated/>
            static class Reflection { static object descriptor; }
            """);
    }
}
