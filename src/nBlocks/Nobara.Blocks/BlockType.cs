using System.Diagnostics.CodeAnalysis;
using Nobara.Core;
using Nobara.Core.Resources;

namespace Nobara.Blocks;

/// <summary>
/// A type of block in the registry, such as <c>block:example.blocks.lamp</c>:
/// its native fields, its state properties, and the range of its states.
/// It describes the type, never a block of the world.
/// </summary>
/// <remarks>
/// <para>
/// The states of a type are contiguous: from <see cref="FirstState"/> to
/// <see cref="FirstState"/> plus <see cref="StateCount"/> minus 1. The native
/// fields of the type are those written in <c>&lt;Content&gt;</c>; a variant
/// may change them for some states, so read the values of a state with the
/// methods of <see cref="IBlockRegistry"/>.
/// </para>
/// <para>
/// There is one instance per type and per context. Keep references to it: a
/// reload of the resources in development mode changes its values in place.
/// Read it on the loop thread of the context.
/// </para>
/// </remarks>
public sealed class BlockType
{
    private Dictionary<string, StateProperty> _byName = new(StringComparer.Ordinal);

    internal BlockType(string objectId, int index, uint firstState, int stateCount, ResourceData data)
    {
        ObjectId = objectId;
        Index = index;
        FirstState = firstState;
        StateCount = stateCount;
        Data = data;
    }

    /// <summary>Gets the object identifier: <c>block:example.blocks.lamp</c>. Disk and network name the type by it.</summary>
    public string ObjectId { get; }

    /// <summary>
    /// Gets the index of the type: 0 for <c>block:nobara.air</c>, then the
    /// other types sorted by identifier, in ordinal order.
    /// </summary>
    public int Index { get; }

    /// <summary>Gets the index of the first state of the type.</summary>
    public uint FirstState { get; }

    /// <summary>Gets the number of states of the type: the product of the number of values of its properties.</summary>
    public int StateCount { get; }

    /// <summary>Gets the state whose properties all have their default value.</summary>
    public uint DefaultState { get; internal set; }

    /// <summary>Gets whether the type is <c>block:nobara.air</c>, whose only state is 0.</summary>
    public bool IsAir => Index == 0;

    /// <summary>Gets the shape object, such as <c>shape:nobara.cube</c>; empty for the air, which has no shape.</summary>
    /// <remarks>nBlocks keeps the identifier without knowing shapes; the module that provides them checks it.</remarks>
    public string Shape { get; internal set; } = string.Empty;

    /// <summary>Gets the collision written in <c>&lt;Content&gt;</c>.</summary>
    public BlockCollision Collision { get; internal set; }

    /// <summary>Gets the opacity written in <c>&lt;Content&gt;</c>.</summary>
    public BlockOpacity Opacity { get; internal set; }

    /// <summary>Gets the hardness written in <c>&lt;Content&gt;</c>; <see cref="float.PositiveInfinity"/> for <c>unbreakable</c>.</summary>
    public float Hardness { get; internal set; }

    /// <summary>Gets the set of orientations of the type.</summary>
    public BlockOrientations Orientations { get; internal set; }

    /// <summary>Gets the cells that a block of the type occupies, relative to its origin, origin first: the index of a cell is its <c>part</c>.</summary>
    public IReadOnlyList<BlockCell> Footprint { get; internal set; } = [];

    /// <summary>
    /// Gets the state properties in index order: <c>orientation</c> and
    /// <c>part</c> when the type has them, then the <c>&lt;Bool&gt;</c>, the
    /// <c>&lt;Int&gt;</c>, and the <c>&lt;Enum&gt;</c> properties, each kind in
    /// the order written.
    /// </summary>
    public IReadOnlyList<StateProperty> Properties { get; private set; } = [];

    /// <summary>Gets the identifier of the item generated by <c>&lt;CreateItem&gt;</c>, such as <c>item:example.blocks.lamp</c>, or an empty string.</summary>
    public string ItemId { get; internal set; } = string.Empty;

    /// <summary>Gets the resource of the type, with its free properties.</summary>
    public ResourceData Data { get; internal set; }

    /// <summary>Gets where the type is written.</summary>
    public SourcePosition Source => Data.Source;

    /// <summary>Gets what the resource declares, read and checked.</summary>
    internal BlockLayout Layout { get; set; } = null!;

    /// <summary>Gets a state property by name.</summary>
    /// <param name="name">The name: <c>lit</c>, or <c>orientation</c> and <c>part</c> for the properties of the engine.</param>
    /// <returns>The property.</returns>
    /// <exception cref="KeyNotFoundException">The type has no property of that name.</exception>
    public StateProperty GetProperty(string name) =>
        TryGetProperty(name, out StateProperty? property) ? property : throw new KeyNotFoundException($"'{ObjectId}' has no state property '{name}'.");

    /// <summary>Finds a state property by name.</summary>
    /// <param name="name">The name.</param>
    /// <param name="property">The property, or <see langword="null"/>.</param>
    /// <returns><see langword="true"/> when the type has the property.</returns>
    public bool TryGetProperty(string name, [NotNullWhen(true)] out StateProperty? property)
    {
        ArgumentNullException.ThrowIfNull(name);
        return _byName.TryGetValue(name, out property);
    }

    /// <summary>Tells whether a state belongs to the type.</summary>
    /// <param name="state">A state index.</param>
    /// <returns><see langword="true"/> when the state is one of the type.</returns>
    [HotPath]
    public bool Contains(uint state) => state - FirstState < (uint)StateCount;

    /// <summary>Tells whether the type is a member of a tag.</summary>
    /// <param name="tag">The tag.</param>
    /// <returns><see langword="true"/> when the type is a member.</returns>
    [HotPath]
    public bool HasTag(BlockTag tag)
    {
        ArgumentNullException.ThrowIfNull(tag);
        return tag.Contains(this);
    }

    /// <summary>Returns the object identifier.</summary>
    /// <returns>The identifier.</returns>
    public override string ToString() => ObjectId;

    internal void SetProperties(IReadOnlyList<StateProperty> properties)
    {
        Properties = properties;
        _byName = properties.ToDictionary(p => p.Name, StringComparer.Ordinal);
    }
}

/// <summary>
/// A state property of a type of block, such as <c>lit</c> or
/// <c>orientation</c>. Each combination of the values of the properties of a
/// type is one state. Values are numbered from 0, in the order of
/// <see cref="Values"/>.
/// </summary>
/// <remarks>
/// Resolve a property once, with <see cref="BlockType.GetProperty"/>, and keep
/// it: reading and changing a value of a state then takes constant time,
/// through <see cref="IBlockRegistry.GetValue"/> and <see cref="IBlockRegistry.With"/>.
/// </remarks>
public sealed class StateProperty
{
    internal StateProperty(BlockType block, string name, StatePropertyKind kind, string[] values, int defaultValue, int min, uint stride)
    {
        Block = block;
        Name = name;
        Kind = kind;
        Values = values;
        Count = values.Length;
        Default = defaultValue;
        Min = min;
        Stride = stride;
    }

    /// <summary>Gets the type of block.</summary>
    public BlockType Block { get; }

    /// <summary>Gets the name: <c>lit</c>.</summary>
    public string Name { get; }

    /// <summary>Gets the kind.</summary>
    public StatePropertyKind Kind { get; }

    /// <summary>Gets the values as written in a state identifier: <c>false</c> and <c>true</c>, the numbers of an <c>&lt;Int&gt;</c>, the names of an <c>&lt;Enum&gt;</c> or of the orientations.</summary>
    public IReadOnlyList<string> Values { get; }

    /// <summary>Gets the number of values.</summary>
    public int Count { get; }

    /// <summary>Gets the number of the default value.</summary>
    public int Default { get; internal set; }

    /// <summary>Gets the number that value 0 stands for: the minimum of an <c>&lt;Int&gt;</c>, 0 otherwise.</summary>
    public int Min { get; }

    /// <summary>Gets the distance between the indices of two states whose only difference is one step of this property.</summary>
    internal uint Stride { get; }

    /// <summary>Gets the number of a value.</summary>
    /// <param name="value">The value as written: <c>true</c>, <c>3</c>, <c>top</c>.</param>
    /// <returns>Its number, or -1 when the property has no such value.</returns>
    public int IndexOf(string value)
    {
        ArgumentNullException.ThrowIfNull(value);
        for (int i = 0; i < Values.Count; i++)
        {
            if (Values[i] == value)
            {
                return i;
            }
        }

        return -1;
    }

    /// <summary>Returns the name.</summary>
    /// <returns>The name.</returns>
    public override string ToString() => Name;
}
